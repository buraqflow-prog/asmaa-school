export const FORBIDDEN_WORDS: string[] = [
  'توحد',
  'مرض',
  'علاج',
  'تشخيص',
  'فشل',
  'خطأ',
  'سيء',
  'درجة',
  'عائلتك',
  'أبوك',
  'أمك',
];

/**
 * Helper to strip Arabic diacritics (Tashkeel) when checking forbidden words
 * so vocalized words like "خَطَأ" or "تَوَحُّد" are still caught reliably.
 */
export function stripArabicDiacritics(text: string): string {
  return text.replace(/[\u064B-\u065F\u0670]/g, '');
}

/**
 * Mandatory Validation Filter (`validateOutput`)
 * - Strips internal thinking tags (<think>...</think>) and surrounding quotes.
 * - Preserves Arabic Tashkeel (diacritics) in `cleanedText` for accurate TTS pronunciation.
 * - Enforces maximum 2 short Arabic sentences (<= 15 words total).
 * - Rejects if it contains ANY forbidden diagnostic/judgmental/personal words.
 */
export function validateOutput(rawText: string): ValidationResult {
  if (!rawText || typeof rawText !== 'string') {
    return {
      valid: false,
      cleanedText: '',
      wordCount: 0,
      sentenceCount: 0,
      rejectedReason: 'النص فارغ أو غير صالح.',
      matchedForbiddenWords: [],
    };
  }

  // 1. Strip internal <think>...</think> tags, markdown blocks, and quotes
  const cleaned = rawText
    .replace(/<think>[\s\S]*?<\/think>/gi, '')
    .replace(/```[\s\S]*?```/g, '')
    .replace(/["'«»“”`]/g, '')
    .replace(/\s+/g, ' ')
    .trim();

  if (!cleaned) {
    return {
      valid: false,
      cleanedText: '',
      wordCount: 0,
      sentenceCount: 0,
      rejectedReason: 'النص فارغ بعد إزالة الوسوم.',
      matchedForbiddenWords: [],
    };
  }

  // 2. Check forbidden words (against un-vocalized normalized text)
  const normalizedWithoutTashkeel = stripArabicDiacritics(cleaned);
  const matchedForbidden: string[] = [];
  for (const word of FORBIDDEN_WORDS) {
    if (normalizedWithoutTashkeel.includes(word)) {
      matchedForbidden.push(word);
    }
  }

  // Split words and sentences
  const words = cleaned.split(/\s+/).filter(Boolean);
  const wordCount = words.length;

  const sentences = cleaned
    .split(/[.!؟?\n]+/)
    .map((s) => s.trim())
    .filter(Boolean);
  const sentenceCount = Math.max(1, sentences.length);

  if (matchedForbidden.length > 0) {
    return {
      valid: false,
      cleanedText: cleaned,
      wordCount,
      sentenceCount,
      rejectedReason: `يحتوي النص على كلمات محظورة تربوياً/تشخيصياً: (${matchedForbidden.join('، ')})`,
      matchedForbiddenWords: matchedForbidden,
    };
  }

  if (sentenceCount > 2) {
    return {
      valid: false,
      cleanedText: cleaned,
      wordCount,
      sentenceCount,
      rejectedReason: `تجاوز الحد الأقصى للجمل (${sentenceCount} جمل، المسموح جملتان كحد أقصى).`,
      matchedForbiddenWords: [],
    };
  }

  if (wordCount > 15) {
    return {
      valid: false,
      cleanedText: cleaned,
      wordCount,
      sentenceCount,
      rejectedReason: `تجاوز الحد الأقصى للكلمات (${wordCount} كلمة، المسموح 15 كلمة كحد أقصى).`,
      matchedForbiddenWords: [],
    };
  }

  return {
    valid: true,
    cleanedText: cleaned,
    wordCount,
    sentenceCount,
    matchedForbiddenWords: [],
  };
}

